/**
 * 글의 {days}·{daysDat} 자리에 넣을 "일수 + 단위". 유예는 1~90일이라 단수가 나올 수 있다 — 단·복수가 갈리는 언어만 가른다.
 * 독일어는 "in … Tagen"(여격)만 {daysDat} 로 따로 쓴다.
 */
export function dayPhrase(lang: Lang, n: number, dative = false): string {
  const one = n === 1
  switch (lang) {
    case 'ko': return `${n}일`
    case 'ja': return `${n}日`
    case 'zh-CN': case 'zh-TW': return `${n} 天`
    case 'en': return one ? '1 day' : `${n} days`
    case 'de': return one ? '1 Tag' : `${n} ${dative ? 'Tagen' : 'Tage'}`
    case 'fr': return one ? '1 jour' : `${n} jours`
    case 'es': return one ? '1 día' : `${n} días`
    case 'pt': return one ? '1 dia' : `${n} dias`
    case 'ru': {
      const form = new Intl.PluralRules('ru').select(n)
      return `${n} ${form === 'one' ? 'день' : form === 'few' ? 'дня' : 'дней'}`
    }
    case 'id': return `${n} hari`
    case 'th': return `${n} วัน`
    case 'vi': return `${n} ngày`
  }
}

